@check_contracts
def find_collision_len_times_sum(message: str) -> str:
    """Return a new message, not equal to the given message, that can be verified using the same signature
    when using the RSA digital signature scheme with the len_times_sum message digest.

    Preconditions:
    - len(message) >= 2
    - any({ord(c) < 1114111 for c in message})
    """
    new_message_so_far = ''
    first = chr(ord(message[0]) - 1)
    new_message_so_far = new_message_so_far + first
    for i in range(1, len(message) - 1):
        new_message_so_far = new_message_so_far + message[i]
    last = chr(ord(message[len(message) - 1]) + 1)
    new_message_so_far = new_message_so_far + last
    return new_message_so_far


